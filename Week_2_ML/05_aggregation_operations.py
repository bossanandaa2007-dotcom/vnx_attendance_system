import numpy as np
# Creating a 1D array
array_1d=np.array([12,15,20,10,18])
print("The Given 1D Array is:",array_1d)
# Aggregation operations
sum_array=np.sum(array_1d) #adding all numbers
print("Sum:",sum_array)
mean_array=np.mean(array_1d) #average of numbers
print(f"Mean:",mean_array)
max_array=np.max(array_1d) #maximum of among number
print("Max:",max_array)
min_array=np.min(array_1d) #minimum among numbers
print("Min:",min_array)
