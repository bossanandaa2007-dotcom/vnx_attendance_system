import numpy as np
#creating 1D array
array_1d=np.array([2,4,6,8,10,12,14])
print("The Given 1D Array is:",array_1d)
#Slicing 1D array
slice_1=array_1d[0:3]
print("First 3 elements:",slice_1)
slice_2=array_1d[1:6]
print("Middle elements:",slice_2)
slice_3=array_1d[5:7]
print("Last 2 elements:",slice_3)